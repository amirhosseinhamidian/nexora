#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from nexora.api import create_app
from nexora.runtime_contracts import GENERATED_MODEL_TYPES, RuntimeModel

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_ROOT = ROOT / "contracts/runtime/v1/schemas"
OPENAPI_PATH = ROOT / "contracts/runtime/v1/openapi.json"
TYPESCRIPT_PATH = ROOT / "packages/contracts/src/generated/runtime-api.ts"
PYTHON_MANIFEST_PATH = ROOT / "apps/server/src/nexora/generated/runtime_contract_manifest.py"


def _json_text(payload: object) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def _canonical_checksum(payload: object) -> str:
    encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode()
    return hashlib.sha256(encoded).hexdigest()


def _schema_filename(model: type[RuntimeModel]) -> str:
    output: list[str] = []
    for index, character in enumerate(model.__name__):
        if character.isupper() and index:
            output.append("-")
        output.append(character.lower())
    return "".join(output) + ".schema.json"


def build_schemas() -> dict[str, dict[str, Any]]:
    return {model.__name__: model.model_json_schema() for model in GENERATED_MODEL_TYPES}


def _typescript_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(_typescript_type(option) for option in schema["anyOf"])
    schema_type = schema.get("type")
    if schema_type == "string":
        return "string"
    if schema_type in {"integer", "number"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        return f"Array<{_typescript_type(schema.get('items', {}))}>"
    if schema_type == "object":
        return "Record<string, unknown>"
    raise ValueError(f"unsupported runtime schema shape: {schema}")


def build_typescript(schemas: dict[str, dict[str, Any]]) -> str:
    checksum = _canonical_checksum(schemas)
    lines = [
        "// Generated by scripts/generate_runtime_contracts.py; do not edit.",
        f'export const runtimeContractChecksum = "{checksum}" as const;',
        "",
    ]
    for name, schema in schemas.items():
        properties = schema.get("properties")
        if not isinstance(properties, dict):
            raise ValueError(f"runtime schema is not an object: {name}")
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for field, field_schema in properties.items():
            optional = "" if field in required else "?"
            lines.append(f"  {field}{optional}: {_typescript_type(field_schema)};")
        lines.extend(("}", ""))
    return "\n".join(lines)


def build_python_manifest(schemas: dict[str, dict[str, Any]]) -> str:
    checksum = _canonical_checksum(schemas)
    names = ",\n".join(f'    "{name}"' for name in schemas)
    return (
        '"""Generated runtime-contract identity; do not edit."""\n\n'
        "from typing import Final\n\n"
        f'RUNTIME_CONTRACT_CHECKSUM: Final = "{checksum}"\n'
        "RUNTIME_CONTRACT_MODELS: Final = (\n"
        f"{names},\n"
        ")\n"
    )


def build_outputs() -> dict[Path, str]:
    schemas = build_schemas()
    outputs = {
        OPENAPI_PATH: _json_text(create_app().openapi()),
        TYPESCRIPT_PATH: build_typescript(schemas),
        PYTHON_MANIFEST_PATH: build_python_manifest(schemas),
    }
    for model in GENERATED_MODEL_TYPES:
        outputs[SCHEMA_ROOT / _schema_filename(model)] = _json_text(schemas[model.__name__])
    return outputs


def validate_fixtures() -> None:
    fixtures = ROOT / "contracts/runtime/v1/fixtures"
    by_name = {model.__name__: model for model in GENERATED_MODEL_TYPES}
    manifest = json.loads((fixtures / "manifest.json").read_text(encoding="utf-8"))
    if not isinstance(manifest, dict) or set(manifest) != {"fixtures", "schema_version"}:
        raise ValueError("runtime fixture manifest is invalid")
    if manifest["schema_version"] != "nexora-runtime-fixtures-v1":
        raise ValueError("runtime fixture manifest version is unknown")
    for entry in manifest["fixtures"]:
        model = by_name.get(entry["model"])
        if model is None:
            raise ValueError(f"runtime fixture references an unknown model: {entry['model']}")
        payload = json.loads((fixtures / entry["path"]).read_text(encoding="utf-8"))
        model.model_validate(payload)


def write_or_check(*, check: bool) -> None:
    drift: list[str] = []
    for path, content in build_outputs().items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                drift.append(path.relative_to(ROOT).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if drift:
        raise SystemExit("runtime contract drift: " + ", ".join(sorted(drift)))
    validate_fixtures()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    write_or_check(check=arguments.check)
    print("NEX_P1_07_RUNTIME_CONTRACT_TOOLCHAIN=PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
